#!/usr/bin/env python3
"""Compile the single editorial JSON to reproducible terminal JSON + file:// JS."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from aegis.catalog import canonical, compile_catalog


def artifacts():
    data = json.loads((ROOT / 'content/editorial.json').read_text())
    compiled = compile_catalog(data, ROOT)
    for source in data['sources']:
        for name, expected in source.get('verification', {}).get('files', {}).items():
            import hashlib
            path = (ROOT / name).resolve()
            if not path.is_relative_to(ROOT) or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
                raise ValueError('A documentação da calculadora precisa ser reconferida: ' + name)
    raw = canonical(compiled).decode()
    # Even accidental </script>, angle brackets and JS line separators stay data.
    escaped = raw.replace('<', '\\u003c').replace('>', '\\u003e').replace('&', '\\u0026').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return {ROOT / 'content/catalog.json': (raw + '\n').encode(),
            ROOT / 'aegis-linux/app/catalog-data.js': ('// Generated by tools/build-catalog.py; edit content/editorial.json.\n' + 'globalThis.AegisCatalog = ' + escaped + ';\n').encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, raw in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != raw:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(raw)
    if stale:
        parser.exit(1, 'Catálogos divergentes: ' + ', '.join(stale) + '\n')
    print('Catálogos consistentes.' if args.check else 'JSON e JavaScript gerados a partir da fonte editorial única.')


if __name__ == '__main__':
    main()
